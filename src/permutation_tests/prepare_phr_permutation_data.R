)

# Extract CenSat type from the names
chm13_censat_gr$type <- tolower(sub("_.*", "", chm13_censat_gr$name))

# Define active alpha satellites based on CenSat color
chm13_censat_gr$type[
  chm13_censat_gr$type == "hor" & chm13_censat_gr$itemRgb == "#990000"
] <- "hor_l"


# Extract the acrocentric short arm regions
acrocentric_regions <- subset(
  chm13_censat_gr,
  seqnames %in% c("chr13", "chr14", "chr15", "chr21", "chr22") & type == "hor_l"
)

# Set all starts to 1
start(acrocentric_regions) <- 1

# Create one unified region for each chromosome
acrocentric_regions <- unlist(
  range(
    split(
      acrocentric_regions,
      seqnames(acrocentric_regions)
    )
  )
)

# Define a list with the files generated by ODGI position
odgi_files <- fs::dir_ls(
  fs::path(res_path, "misc"),
  glob = "*acro_short_arms.position.chr*.tsv"
)

# Read all ODGI position files
odgi_pos_res <- purrr::map(
  odgi_files,
  ~ read_tsv(
    .x,
    skip = 1,
    show_col_types = FALSE,
    col_names = c(
      "query_chrom", "query_start", "query_end",
      "query_name", "query_strand",
      "ref_start", "ref_end", "ref_strand"
    )
  )
) |>
  purrr::list_rbind() |>
  # Tidy data so that we reach a BEDPE like format
  dplyr::mutate(
    query_chrom = str_split_i(query_chrom, "#", 1),
    ref_chrom = str_split_i(ref_start, "#", 1),
    ref_start = as.numeric(str_split_i(ref_start, ",", 2)),
    ref_end = as.numeric(str_split_i(ref_end, ",", 2)),
    ref_start   = pmin(ref_start, ref_end),
    ref_end     = pmax(ref_start, ref_end),
    query_width = query_end - query_start,
    ref_width = ref_end - ref_start
  ) |>
  dplyr::arrange(
    query_chrom, query_start, query_end,
    ref_chrom, ref_start, ref_end,
  ) |>
  # Select only positions that are the same length as the CTCF site we analyze
  dplyr::filter(
    query_width == ref_width
  ) |>
  dplyr::select(
    query_chrom, query_start, query_end,
    query_strand, query_width, ref_chrom,
    ref_start, ref_end, ref_strand, ref_width
  )

# Create a GRanges object with the lifted over positions
target_gr <- GRanges(
  seqnames = odgi_pos_res$ref_chrom,
  ranges   = IRanges(
    start = odgi_pos_res$ref_start,
    end = odgi_pos_res$ref_end
  )
)

# Find which lifted over positions overlap exactly with CTCF sites
hits <- findOverlaps(
  chm13_gr,
  target_gr,
  type = "within",
  ignore.strand = TRUE
)

# Add a flag if they are CTCF sites
odgi_pos_res$is_ctcf <- as.integer(
  seq_along(target_gr) %in% subjectHits(hits)
)

# Keep only regions that are CTCF sites in both original
# and lifted over coordintates
odgi_pos_res <- odgi_pos_res |>
  filter(is_ctcf == 1)

# Calculate across how many arms each short arm
# CTCF site appears in
stats_per_site <- odgi_pos_res |>
  dplyr::group_by(
    query_chrom,
    query_start,
    query_end
  ) |>
  dplyr::summarise(
    n_targets = dplyr::n(),
    is_ctcf = as.integer(any(is_ctcf == 1)),
    .groups = "drop"
  )

# Add a label in how many arms it appears in
stats_per_site <- stats_per_site |>
  dplyr::mutate(
    category = case_when(
      n_targets == 1 ~ "1 arm",
      TRUE ~ paste0(n_targets, " arms")
    )
  )

# Create a helper function to filter the data to contain sites
# present in one or multiple arms
subset_acro_sites <- function(stats_per_site, one_arm_only) {
  one_arm <- "1 arm"

  filtered <- if (one_arm_only) {
    dplyr::filter(stats_per_site, .data$category == one_arm)
  } else {
    dplyr::filter(stats_per_site, .data$category != one_arm)
  }

  GenomicRanges::makeGRangesFromDataFrame(
    filtered,
    keep.extra.columns = TRUE,
    seqnames.field = "query_chrom",
    start.field    = "query_start",
    end.field      = "query_end"
  )
}

# Subset short arm CTCF sites
single_arm_ctcf_sites_gr <- subset_acro_sites(stats_per_site, TRUE)
multiple_arm_ctcf_sites_gr <- subset_acro_sites(stats_per_site, FALSE)

