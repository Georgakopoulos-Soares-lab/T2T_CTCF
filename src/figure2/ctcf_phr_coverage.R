# Create a helper function to filter the data to contain sites
# present in one or multiple arms
subset_acro_sites <- function(stats_per_site, one_arm_only) {
  one_arm <- "1 arm"

  filtered <- if (one_arm_only) {
    dplyr::filter(stats_per_site, .data$category == one_arm)
  } else {
    dplyr::filter(stats_per_site, .data$category != one_arm)
  }

  GenomicRanges::makeGRangesFromDataFrame(
    filtered,
    keep.extra.columns = TRUE,
    seqnames.field = "query_chrom",
    start.field    = "query_start",
    end.field      = "query_end"
  )
}

